# 校验：_review.txt 的行号 -> 原文本，确保行号没对错
review = {}
for line in io.open(os.path.join(META, "_review.txt"), encoding="utf-8"):
    parts = line.rstrip("\n").split("|")
    if len(parts) >= 4:
        review[int(parts[0])] = (parts[1], parts[2])

src_lines = [l for l in io.open(SRC, encoding="utf-8").read().splitlines() if l]
assert len(src_lines) == len(review), "行数不一致: %d vs %d" % (len(src_lines), len(review))

changes = []
out = []
for idx, line in enumerate(src_lines, 1):
    wav, spk, lang, text = line.split("|", 3)
    fn = review[idx][0]
    if idx in FIXES:
        new, kind, why = FIXES[idx]
        if text == new:
            print("  !! 行 %d (%s) 新旧相同，跳过" % (idx, fn))
        else:
            changes.append((idx, fn, text, new, kind, why))
            text = new
    out.append("%s|%s|%s|%s" % (wav, spk, lang, text))

if not os.path.exists(BAK):
    shutil.copy2(SRC, BAK)
    print("已备份 ->", BAK)

io.open(DST, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

print("共修改 %d 条 / 总 %d 条" % (len(changes), len(src_lines)))
print()
by_kind = {}
for c in changes:
    by_kind.setdefault(c[4], 0)
    by_kind[c[4]] += 1
print("按类别:", by_kind)
print()

with io.open(os.path.join(META, "_jingjiao_changelog.txt"), "w", encoding="utf-8") as f:
    f.write("schinese_dark_willow_vo_pure.list 精校记录（共 %d 条）\n" % len(changes))
    f.write("类别: A=官方文本对齐  B=专有名词  C=同音错字  D=语法/标点\n")
    f.write("=" * 100 + "\n")
    for idx, fn, old, new, kind, why in changes:
        f.write("%3d  %-24s [%s]\n" % (idx, fn, kind))
        f.write("     原: %s\n" % old)
        f.write("     改: %s\n" % new)
        f.write("     因: %s\n\n" % why)
print("改动清单 -> _jingjiao_changelog.txt")
